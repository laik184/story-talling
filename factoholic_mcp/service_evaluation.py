from __future__ import annotations
from .service_shared import *

class EvaluationOperations:
    def scan_originality(self, script: str) -> OriginalityResult:
        if not script.strip() or len(script) > MAX_SCRIPT_CHARS:
            raise ServiceError("invalid_input", f"script must be 1–{MAX_SCRIPT_CHARS} characters")
        if not self._scan_slots.acquire(timeout=2):
            raise ServiceError("service_busy", "Originality scan capacity is temporarily full; retry shortly.")
        try:
            result = self.originality_scanner.scan(script)
        except FileNotFoundError as exc:
            raise ServiceError("corpus_unavailable", "The authorized local transcript corpus is unavailable.") from exc
        except OSError as exc:
            LOGGER.warning("originality scan failed (%s)", type(exc).__name__)
            raise ServiceError("corpus_read_failed", "The local originality scan could not read its corpus.") from exc
        finally:
            self._scan_slots.release()
        return OriginalityResult(
            lexical_status=str(result.get("status", "unknown")),
            longest_exact_run_tokens=int(result.get("longest_exact_run_tokens", 0)),
            matching_video_count=int(result.get("matching_video_count", 0)),
            matched_fraction=float(result.get("matched_fraction", 0.0)),
            near_match_score=float(result.get("near_match_score", 0.0)),
            matched_evidence_video_id=result.get("matched_video_id"),
            corpus_file_count=int(result.get("corpus_file_count", 0)),
            limitations=str(result.get("limitations", "")),
            human_semantic_review_required=True,
        )

    def evaluate_script(self, topic: str, script: str, target_duration_seconds: int,
                        evidence: EvidencePackInput | None = None,
                        claim_map: list[ClaimEvidenceInput] | None = None) -> EvaluationResult:
        self._validate_request(topic, None)
        if not script.strip() or len(script) > MAX_SCRIPT_CHARS:
            raise ServiceError("invalid_input", f"script must be 1–{MAX_SCRIPT_CHARS} characters")
        if not 15 <= target_duration_seconds <= 180:
            raise ServiceError("invalid_input", "target_duration_seconds must be between 15 and 180")
        word_count = len(tokens(script))
        estimate = round(word_count * 60 / WORDS_PER_MINUTE, 1)
        delta = (estimate - target_duration_seconds) / target_duration_seconds
        duration_check = "within_15_percent_estimate" if abs(delta) <= 0.15 else ("shorter_than_target_estimate" if delta < 0 else "longer_than_target_estimate")

        facts_by_id = {fact.fact_id: fact for fact in evidence.facts} if evidence else {}
        if claim_map and len(claim_map) > 50:
            raise ServiceError("invalid_claim_map", "claim_map may contain at most 50 claims")
        claim_rows: list[ClaimBindingResult] = []
        seen_claim_ids: set[str] = set()
        for claim in claim_map or []:
            if claim.claim_id in seen_claim_ids:
                raise ServiceError("duplicate_claim_id", "claim_map claim_id values must be unique")
            seen_claim_ids.add(claim.claim_id)
            unknown = sorted(set(claim.evidence_fact_ids) - facts_by_id.keys())
            status = "unbound" if not claim.evidence_fact_ids else ("unknown_fact_id" if unknown else "bound_by_id_only")
            claim_rows.append(ClaimBindingResult(
                claim_id=claim.claim_id,
                supplied_fact_ids=claim.evidence_fact_ids,
                unknown_fact_ids=unknown,
                binding_status=status,
            ))
        referenced = {fact_id for row in claim_rows for fact_id in row.supplied_fact_ids if fact_id in facts_by_id}

        rubric = [RubricDimension(
            dimension_id=dimension["id"],
            question=dimension["question"],
            score_anchors=dimension["score_behavior"],
        ) for dimension in self.rubric["dimensions"]]
        originality = self.scan_originality(script)
        return EvaluationResult(
            topic=topic.strip(),
            word_count=word_count,
            estimated_spoken_seconds=estimate,
            target_duration_seconds=target_duration_seconds,
            duration_check=duration_check,
            originality=originality,
            claim_bindings=claim_rows,
            unreferenced_fact_ids=sorted(facts_by_id.keys() - referenced),
            rubric_for_chatgpt=rubric,
            factual_gate="not_semantically_assessed",
            quality_scores=None,
            limitations=[
                "Duration is a word-rate estimate; actual delivery pace, pauses, and pronunciation are not measured.",
                "Fact IDs establish structural linkage only. The tool does not decide whether a claim is supported by source text.",
                "Dimension scores are deliberately not generated by this deterministic tool; ChatGPT or a human must apply the rubric.",
                "The originality result is a local lexical screen, not semantic proof; human review remains required.",
            ],
        )

